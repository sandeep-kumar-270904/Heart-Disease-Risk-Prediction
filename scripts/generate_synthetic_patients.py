"""HeartXAI 2.0 — Category B Synthetic Patient Fixture Generator.

Generates synthetically sampled application test cohorts using parametric marginal
distributions documented in ``shared/data-dictionary.json``.

GOVERNANCE & PRIVACY INVARIANTS (Phase 12.2.5 / 12.2.6 / DEC-005):
1. Category B Fixture Scope Only: Records generated by this script are strictly for
   UI development, API contract testing, staging smoke checks, and demo personas.
2. Strict ML Separation: Synthetic records MUST NEVER be mixed into machine learning
   training, cross-validation, calibration, or evaluation datasets.
3. Zero Row Copying: This generator does NOT read, copy, or memorize individual rows
   from ``processed.cleveland.data``. Parameters are drawn solely from documented
   cohort-level marginal summaries in ``shared/data-dictionary.json``.
4. No Differential Privacy Claim: No formal (epsilon, delta)-differential privacy
   mechanism is implemented in this script. Residual parametric similarity caveats
   are documented in Phase 12.2.5 and Phase 12.2.6 governance reports.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np

# Ensure backend package is importable when running as a standalone script
REPO_ROOT = Path(__file__).resolve().parent.parent
BACKEND_DIR = REPO_ROOT / "backend"
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

from app.schemas.assessment import (  # noqa: E402
    CHOLESTEROL_MMOL_TO_MGDL,
    GLUCOSE_MMOL_TO_MGDL,
    AssessmentCreateDto,
    SyntheticPatientRecord,
)
from app.schemas.auth import UnitSystem  # noqa: E402

GENERATOR_VERSION = "1.0.0"
DATA_DICTIONARY_PATH = REPO_ROOT / "shared" / "data-dictionary.json"


def load_data_dictionary(path: Path = DATA_DICTIONARY_PATH) -> dict[str, Any]:
    """Load canonical clinical feature bounds and marginal statistics."""
    with path.open("r", encoding="utf-8") as handle:
        data: dict[str, Any] = json.load(handle)
    return data


def _sample_bounded_normal(
    rng: np.random.Generator,
    mean: float,
    std: float,
    low: float,
    high: float,
    decimals: int = 1,
) -> float:
    """Sample a continuous biomarker from a clipped normal distribution."""
    raw = float(rng.normal(loc=mean, scale=std))
    clipped = min(max(raw, low), high)
    return round(clipped, decimals)


def _sample_categorical(
    rng: np.random.Generator,
    proportions: dict[str, float],
) -> int:
    """Sample a discrete integer category according to marginal weights."""
    keys = [int(k) for k in proportions]
    probs = np.array([proportions[str(k)] for k in keys], dtype=float)
    probs = probs / probs.sum()
    return int(rng.choice(keys, p=probs))


def generate_synthetic_cohort(
    count: int = 50,
    seed: int = 42,
    unit_system: UnitSystem = "us_customary",
    dictionary_path: Path = DATA_DICTIONARY_PATH,
) -> list[SyntheticPatientRecord]:
    """Generate ``count`` schema-validated Category B synthetic patient records."""
    if count < 1:
        raise ValueError("count must be >= 1")

    data_dict = load_data_dictionary(dictionary_path)
    biomarkers = {item["id"]: item for item in data_dict["biomarkers"]}
    rng = np.random.default_rng(seed)
    timestamp = datetime.now(UTC)

    records: list[SyntheticPatientRecord] = []
    for idx in range(1, count + 1):
        age = _sample_bounded_normal(
            rng,
            mean=biomarkers["age"]["empirical_stats"]["mean"],
            std=biomarkers["age"]["empirical_stats"]["std"],
            low=biomarkers["age"]["min"],
            high=biomarkers["age"]["max"],
            decimals=0,
        )
        sex = _sample_categorical(
            rng, biomarkers["sex"]["empirical_stats"]["proportions"]
        )
        cp = _sample_categorical(
            rng, biomarkers["cp"]["empirical_stats"]["proportions"]
        )
        trestbps = _sample_bounded_normal(
            rng,
            mean=biomarkers["trestbps"]["empirical_stats"]["mean"],
            std=biomarkers["trestbps"]["empirical_stats"]["std"],
            low=biomarkers["trestbps"]["min"],
            high=biomarkers["trestbps"]["max"],
            decimals=0,
        )
        chol_mgdl = _sample_bounded_normal(
            rng,
            mean=biomarkers["chol"]["empirical_stats"]["mean"],
            std=biomarkers["chol"]["empirical_stats"]["std"],
            low=biomarkers["chol"]["canonical_min_mgdl"],
            high=biomarkers["chol"]["canonical_max_mgdl"],
            decimals=0,
        )

        # Sample fasting blood sugar concentration consistent with binary proportion
        fbs_stats = biomarkers["fbs"]["empirical_stats"]
        is_elevated_fbs = bool(rng.random() < fbs_stats["gt_120_proportion"])
        if is_elevated_fbs:
            fbs_mgdl = _sample_bounded_normal(
                rng,
                mean=fbs_stats["elevated_mean_mgdl"],
                std=fbs_stats["elevated_std_mgdl"],
                low=121.0,
                high=biomarkers["fbs"]["max"],
                decimals=0,
            )
        else:
            fbs_mgdl = _sample_bounded_normal(
                rng,
                mean=fbs_stats["normal_mean_mgdl"],
                std=fbs_stats["normal_std_mgdl"],
                low=65.0,
                high=120.0,
                decimals=0,
            )

        if unit_system == "metric":
            chol_input = round(chol_mgdl / CHOLESTEROL_MMOL_TO_MGDL, 2)
            fbs_input = round(fbs_mgdl / GLUCOSE_MMOL_TO_MGDL, 2)
        else:
            chol_input = chol_mgdl
            fbs_input = fbs_mgdl

        restecg = _sample_categorical(
            rng, biomarkers["restecg"]["empirical_stats"]["proportions"]
        )
        thalach = _sample_bounded_normal(
            rng,
            mean=biomarkers["thalach"]["empirical_stats"]["mean"],
            std=biomarkers["thalach"]["empirical_stats"]["std"],
            low=biomarkers["thalach"]["min"],
            high=biomarkers["thalach"]["max"],
            decimals=0,
        )
        exang = _sample_categorical(
            rng, biomarkers["exang"]["empirical_stats"]["proportions"]
        )
        oldpeak = _sample_bounded_normal(
            rng,
            mean=biomarkers["oldpeak"]["empirical_stats"]["mean"],
            std=biomarkers["oldpeak"]["empirical_stats"]["std"],
            low=biomarkers["oldpeak"]["min"],
            high=biomarkers["oldpeak"]["max"],
            decimals=1,
        )
        slope = _sample_categorical(
            rng, biomarkers["slope"]["empirical_stats"]["proportions"]
        )

        # Simulate realistic optional missingness for imaging attributes (~2% missingness)
        ca: int | None = (
            None
            if rng.random() < 0.02
            else _sample_categorical(
                rng, biomarkers["ca"]["empirical_stats"]["proportions"]
            )
        )
        thal: int | None = (
            None
            if rng.random() < 0.02
            else _sample_categorical(
                rng, biomarkers["thal"]["empirical_stats"]["proportions"]
            )
        )

        intake = AssessmentCreateDto(
            synthetic_fixture_confirmed=True,
            age=age,
            sex=sex,
            chest_pain_type=cp,
            unit_system=unit_system,
            resting_bp=trestbps,
            serum_cholesterol=chol_input,
            fasting_blood_sugar=fbs_input,
            resting_ecg=restecg,
            max_heart_rate=thalach,
            exercise_angina=exang,
            st_depression=oldpeak,
            st_slope=slope,
            major_vessels=ca,
            thallium_stress=thal,
        )

        record = SyntheticPatientRecord(
            is_synthetic=True,
            mrn=f"SYN-2026-{idx:05d}",
            patient_name=f"Synthetic Patient #{idx:03d}",
            synthetic_generator_version=GENERATOR_VERSION,
            generation_timestamp=timestamp,
            intake=intake,
        )
        records.append(record)

    return records


def main() -> int:
    """CLI entrypoint for generating Category B synthetic test cohorts."""
    parser = argparse.ArgumentParser(
        description="Generate Category B synthetic patient application fixtures (zero real PHI)."
    )
    parser.add_argument(
        "--count", type=int, default=50, help="Number of records to generate"
    )
    parser.add_argument("--seed", type=int, default=42, help="Deterministic PRNG seed")
    parser.add_argument(
        "--unit-system",
        choices=["us_customary", "metric"],
        default="us_customary",
        help="Unit system for input payloads",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Optional output JSON path (defaults to stdout summary)",
    )
    args = parser.parse_args()

    cohort = generate_synthetic_cohort(
        count=args.count,
        seed=args.seed,
        unit_system=args.unit_system,
    )
    serialized = [item.model_dump(mode="json") for item in cohort]

    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        with args.output.open("w", encoding="utf-8") as handle:
            json.dump(serialized, handle, indent=2)
        print(f"Generated {len(cohort)} Category B synthetic records -> {args.output}")
    else:
        print(json.dumps(serialized[:2], indent=2))
        print(f"... Total validated Category B synthetic records: {len(cohort)}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
